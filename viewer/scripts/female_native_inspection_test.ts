import assert from 'node:assert/strict';
import { NullEngine, Scene } from '@babylonjs/core';
import createModel from '../models/female-tactical/createFemaleTacticalModel';
import spec from '../models/female-tactical/spec.json';
import { sculptSpec } from '../models/female-tactical/createNativeFemaleTactical';
import { SculptInspection } from '../src/sculpt/inspection';
import type { SculptSpec } from '../src/sculpt/types';
const engine=new NullEngine(); const scene=new Scene(engine);
const serializedSource=JSON.stringify(sculptSpec);
const model=createModel(scene,{physics:false});
const state=new SculptInspection(model,spec as unknown as SculptSpec);
assert.equal(Object.keys(model.meshes).length,125);
const head=model.meshes.head;
const before=head.computeWorldMatrix(true).getTranslation().clone();
state.isolate('hair');
assert.equal(head.isVisible,false);
assert.equal(model.meshes['hair-cap'].isVisible,true);
state.reset(); assert.equal(head.isVisible,true);
state.explode(1);
assert.ok(head.computeWorldMatrix(true).getTranslation().subtract(before).length()>.1);
state.reset();
assert.ok(head.computeWorldMatrix(true).getTranslation().subtract(before).length()<1e-7);
assert.equal(Object.values(model.meshes).every(m=>m.isPickable),true);
model.dispose();model.dispose();
assert.equal(JSON.stringify(sculptSpec),serializedSource);
const second=createModel(scene,{physics:false});
assert.ok(second.meshes.head.computeWorldMatrix(true).getTranslation().subtract(before).length()<1e-7);
second.dispose();
assert.equal(JSON.stringify(sculptSpec),serializedSource);
scene.dispose();engine.dispose();
console.log('PASS: same 125 native parts, group isolation, explode world displacement/reset, pickability and idempotent dispose');
